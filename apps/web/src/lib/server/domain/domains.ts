import { AddCustomDomain, type CustomDomain } from '@tramline/contracts';
import { and, eq } from 'drizzle-orm';
import { resolveTxt as dnsResolveTxt } from 'node:dns/promises';
import { randomBytes } from 'node:crypto';
import { AppError, notFound } from '../api/errors';
import type { DbOrTx } from '../db/client';
import { customDomain, project, service, serviceInstance } from '../db/schema';
import { publish } from '../events';
import { newId } from '../ids';
import { notifyNodes } from '../nodes/bus';
import { requireInstance } from './access';
import type { Ctx } from './context';

type Row = typeof customDomain.$inferSelect;
export type ResolveTxt = (name: string) => Promise<string[][]>;

/** Pending domains are re-checked this often, and given up on after a week. */
export const RECHECK_MS = 5 * 60_000;
export const GIVE_UP_MS = 7 * 24 * 3600_000;

export const verificationName = (hostname: string) => `_tramline.${hostname}`;
const verificationValue = (token: string) => `tramline-verify=${token}`;

/** Names that can never resolve publicly, so there is nothing to prove. */
const isLocal = (hostname: string) => hostname === 'localhost' || hostname.endsWith('.localhost');

function dto(row: Row, target: string | null): CustomDomain {
	return {
		id: row.id,
		serviceId: row.serviceId,
		environmentId: row.environmentId,
		hostname: row.hostname,
		status: row.status,
		verification: { name: verificationName(row.hostname), value: verificationValue(row.token) },
		target,
		error: row.error,
		checkedAt: row.checkedAt?.toISOString() ?? null,
		verifiedAt: row.verifiedAt?.toISOString() ?? null
	};
}

function generatedDomain(db: DbOrTx, serviceId: string, environmentId: string) {
	return (
		db
			.select({ domain: serviceInstance.domain })
			.from(serviceInstance)
			.where(
				and(
					eq(serviceInstance.serviceId, serviceId),
					eq(serviceInstance.environmentId, environmentId)
				)
			)
			.get()?.domain ?? null
	);
}

export function list(ctx: Ctx, serviceId: string, environmentId: string): CustomDomain[] {
	requireInstance(ctx, serviceId, environmentId);
	const target = generatedDomain(ctx.db, serviceId, environmentId);
	return ctx.db
		.select()
		.from(customDomain)
		.where(
			and(eq(customDomain.serviceId, serviceId), eq(customDomain.environmentId, environmentId))
		)
		.orderBy(customDomain.hostname)
		.all()
		.map((row) => dto(row, target));
}

/** Adds a domain, pending until its TXT record is found. */
export async function add(
	ctx: Ctx,
	input: AddCustomDomain,
	resolveTxt: ResolveTxt = dnsResolveTxt
): Promise<CustomDomain> {
	const { serviceId, environmentId, hostname } = AddCustomDomain.parse(input);
	const { service: svc } = requireInstance(ctx, serviceId, environmentId);
	const base = ctx.settings.baseDomain;
	// generated names belong to Tramline; letting a service claim one would let it take over another's
	// (a local `localhost` install only refuses the generated names that exist)
	const local = base === 'localhost' || base.endsWith('.localhost');
	if (!local && (hostname === base || hostname.endsWith(`.${base}`))) {
		throw new AppError('validation_failed', `Names under ${base} are generated by Tramline`);
	}
	const generated = ctx.db
		.select({ domain: serviceInstance.domain })
		.from(serviceInstance)
		.where(eq(serviceInstance.domain, hostname))
		.get();
	if (generated) throw new AppError('conflict', `${hostname} is already in use`);
	if (ctx.settings.publicUrl && new URL(ctx.settings.publicUrl).hostname === hostname) {
		throw new AppError('validation_failed', 'That is the address of Tramline itself');
	}
	const taken = ctx.db
		.select({ id: customDomain.id })
		.from(customDomain)
		.where(eq(customDomain.hostname, hostname))
		.get();
	if (taken) throw new AppError('conflict', `${hostname} is already in use`);

	const row = ctx.db
		.insert(customDomain)
		.values({
			id: newId('domain'),
			serviceId,
			environmentId,
			hostname,
			token: randomBytes(16).toString('hex'),
			status: 'pending'
		})
		.returning()
		.get();
	publish({ type: 'services', projectId: svc.projectId, serviceId });
	return check(ctx.db, row, resolveTxt);
}

function requireDomain(ctx: Ctx, id: string) {
	const row = ctx.db
		.select({ customDomain, projectId: project.id })
		.from(customDomain)
		.innerJoin(service, eq(customDomain.serviceId, service.id))
		.innerJoin(project, eq(service.projectId, project.id))
		.where(and(eq(customDomain.id, id), eq(project.organizationId, ctx.organizationId)))
		.get();
	if (!row) throw notFound('Domain');
	return row;
}

/** Looks for the TXT record now. */
export async function verify(
	ctx: Ctx,
	id: string,
	resolveTxt: ResolveTxt = dnsResolveTxt
): Promise<CustomDomain> {
	const { customDomain: row } = requireDomain(ctx, id);
	return check(ctx.db, row, resolveTxt);
}

export function remove(ctx: Ctx, id: string) {
	const { customDomain: row, projectId } = requireDomain(ctx, id);
	ctx.db.delete(customDomain).where(eq(customDomain.id, id)).run();
	if (row.status === 'verified') notifyNodes();
	publish({ type: 'services', projectId, serviceId: row.serviceId });
}

/** Checks one domain's TXT record and records the outcome. */
async function check(
	db: DbOrTx,
	row: Row,
	resolveTxt: ResolveTxt,
	now = new Date()
): Promise<CustomDomain> {
	let verified = row.status === 'verified';
	let error: string | null = null;
	if (!verified) {
		if (isLocal(row.hostname)) {
			verified = true;
		} else {
			try {
				const records = (await resolveTxt(verificationName(row.hostname))).map((parts) =>
					parts.join('')
				);
				verified = records.includes(verificationValue(row.token));
				if (!verified) {
					error = records.length
						? `The TXT record at ${verificationName(row.hostname)} doesn't match yet`
						: `No TXT record at ${verificationName(row.hostname)} yet`;
				}
			} catch (cause) {
				const code = (cause as { code?: string }).code;
				error =
					code === 'ENOTFOUND' || code === 'ENODATA'
						? `No TXT record at ${verificationName(row.hostname)} yet`
						: `Couldn't look up ${verificationName(row.hostname)}: ${code ?? (cause as Error).message}`;
			}
		}
	}
	const updated = db
		.update(customDomain)
		.set({
			status: verified ? 'verified' : 'pending',
			error,
			checkedAt: now,
			verifiedAt: verified ? (row.verifiedAt ?? now) : null
		})
		.where(eq(customDomain.id, row.id))
		.returning()
		.get()!;
	// a newly verified domain starts routing straight away
	if (verified && row.status !== 'verified') notifyNodes();
	return dto(updated, generatedDomain(db, row.serviceId, row.environmentId));
}

/** Re-checks pending domains in the background, for a week after they were added. */
export async function recheckDomains(
	db: DbOrTx,
	{ now = new Date(), resolveTxt = dnsResolveTxt }: { now?: Date; resolveTxt?: ResolveTxt } = {}
) {
	const due = db
		.select()
		.from(customDomain)
		.where(eq(customDomain.status, 'pending'))
		.all()
		.filter(
			(row) =>
				now.getTime() - row.createdAt.getTime() < GIVE_UP_MS &&
				(!row.checkedAt || now.getTime() - row.checkedAt.getTime() >= RECHECK_MS)
		);
	for (const row of due) await check(db, row, resolveTxt, now);
	return due.length;
}

/** Verified custom hostnames per service instance, for ingress routes. */
export function verifiedHostnames(db: DbOrTx) {
	return Map.groupBy(
		db.select().from(customDomain).where(eq(customDomain.status, 'verified')).all(),
		(row) => `${row.serviceId}:${row.environmentId}`
	);
}
